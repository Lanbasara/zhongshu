test('capacity fences new work/uploads while preserving archive, receipts, stop and identity; expansion resumes admission', t => {
  const root = mkdtempSync(join(tmpdir(), 'zhongshu-capacity-'));
  const db = openDatabase(root, productMigrations);
  t.after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
  let usedBytes = 0; let freeBytes = 1024 ** 3;
  const quotaBytes = 8 * 1024 ** 2;
  const options = { quotaBytes, reserveBytes: 2 * 1024 ** 2, minimumFreeBytes: 1024 ** 2, sample: () => ({ usedBytes, freeBytes }) };
  let store = createWorkbenchStore(db, { capacity: options }); const id = randomUUID();
  const input = { id, harnessId: 'codex' as const, workspaceId: 'fixture', cwd: '/synthetic', configuration: { modelId: 'fixture', permissionId: 'fixture' } };
  store.createConversation(input);
  const message = { id: randomUUID(), conversationId: id, type: 'message' as const, payload: { text: 'admitted input' } };
  store.enqueueOperation(message); store.claimOperation(message.id);
  store.mergeHistory(id, [{ id: 'saved', kind: 'assistant', status: 'completed', text: 'permanent archive' }]);
  usedBytes = quotaBytes - options.reserveBytes;
  assert.equal(store.capacity().status, 'full');
  assert.throws(() => store.createConversation({ ...input, id: randomUUID() }), { code: 'storage_capacity_reached' });
  assert.throws(() => store.enqueueOperation({ ...message, id: randomUUID() }), { code: 'storage_capacity_reached' });
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6ZAAAAABJRU5ErkJggg==', 'base64');
  assert.throws(() => store.resources.put(id, 'synthetic.png', image), { code: 'storage_capacity_reached' });
  assert.equal(store.createConversation(input).created, false); assert.equal(store.enqueueOperation(message).created, false);
  store.settleOperation(message.id, { outcome: 'accepted', runId: 'native-run' });
  store.enqueueOperation({ id: randomUUID(), conversationId: id, type: 'stop', payload: { runId: 'native-run' } });
  store.mergeHistory(id, [{ id: 'admitted-final', kind: 'assistant', status: 'completed', text: 'accepted work still archives' }]);
  assert.equal(store.getItem(id, 'saved')?.text, 'permanent archive');
  usedBytes = quotaBytes;
  assert.throws(() => store.mergeHistory(id, [{ id: 'cannot-publish', kind: 'assistant', status: 'completed', text: 'never claim saved' }]), { code: 'storage_capacity_reached' });
  assert.equal(store.getItem(id, 'cannot-publish'), null); assert.equal(store.getItem(id, 'saved')?.text, 'permanent archive');
  store = createWorkbenchStore(db, { capacity: { ...options, quotaBytes: quotaBytes * 2 } });
  assert.equal(store.createConversation({ ...input, id: randomUUID() }).created, true);
  freeBytes = 0;
  assert.throws(() => store.createConversation({ ...input, id: randomUUID() }), { code: 'storage_capacity_reached' });
  assert.equal(store.getItem(id, 'saved')?.text, 'permanent archive');
});

test('capacity includes product caches and WAL, traverses in bounded slices, and recovers with hysteresis', async t => {
  const root = mkdtempSync(join(tmpdir(), 'zhongshu-capacity-files-'));
  const db = openDatabase(root, productMigrations);
  const guard = createCapacityGuard(db, { quotaBytes: 128 * 1024 ** 2, reserveBytes: 0, minimumFreeBytes: 0 });
  t.after(() => { guard.close(); db.close(); rmSync(root, { recursive: true, force: true }); });
  const cache = join(root, 'directory-index'); mkdirSync(cache);
  for (let i = 0; i < 400; i++) writeFileSync(join(cache, `${i}.bin`), Buffer.alloc(4096));
  assert.equal(guard.status().status, 'unknown'); assert.equal(guard.pending(), true);
  let steps = 1; while (guard.pending()) { guard.status(); steps++; assert.ok(steps < 10); }
  assert.ok(steps >= 4);
  const file = String(db.prepare('PRAGMA database_list').get()!.file);
  const status = guard.status();
  assert.ok(status.usedBytes >= 400 * 4096 + statSync(file).size + statSync(file + '-wal').size);
  let usedBytes = 8 * 1024 ** 2;
  const hysteresis = createCapacityGuard(db, { quotaBytes: usedBytes, reserveBytes: 0, minimumFreeBytes: 0, sample: () => ({ usedBytes, freeBytes: 1024 ** 3 }) });
  assert.equal(hysteresis.status().status, 'full');
  usedBytes -= 1; assert.equal(hysteresis.status().status, 'full');
  usedBytes -= 128 * 1024; assert.notEqual(hysteresis.status().status, 'full');
});

test('body staging has a global byte budget, unknown stages survive age/restart, superseded chunks collect in bounded batches and old publications remain', t => {
  const root = mkdtempSync(join(tmpdir(), 'zhongshu-capacity-stage-'));
  let db = openDatabase(root, productMigrations);
  t.after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
  const options = { capacity: { transientBytes: 14 * 65536 } };
  let store = createWorkbenchStore(db, options); const id = randomUUID();
  store.createConversation({ id, harnessId: 'codex', workspaceId: 'fixture', cwd: '/synthetic', configuration: { modelId: 'fixture', permissionId: 'fixture' } });
  const bytes = Buffer.alloc(12 * 65536, 'a');
  const ref = { version: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length };
  const revision = { generation: 'source', sequence: 1 };
  const stage = store.beginBodyStage(id, 'item', 'text', ref, revision);
  const rejected = { version: createHash('sha256').update('another import').digest('hex'), bytes: 3 * 65536 };
  assert.throws(() => store.beginBodyStage(id, 'other', 'text', rejected), { code: 'body_staging_capacity_reached' });
  for (let offset = 0; offset < bytes.length; offset += 65536) store.stageBodyChunk(stage.stageId, offset, bytes.subarray(offset, offset + 65536));
  db.prepare('UPDATE workbench_body_stages SET created_at=0').run();
  for (let i = 0; i < 3; i++) store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT transient_bytes FROM workbench_body_usage').get()!.transient_bytes, bytes.length);
  db.close(); db = openDatabase(root, productMigrations); store = createWorkbenchStore(db, options);
  assert.equal(store.beginBodyStage(id, 'item', 'text', ref, revision).nextOffset, bytes.length);
  const replacement = Buffer.alloc(65536, 'b'); const next = { version: createHash('sha256').update(replacement).digest('hex'), bytes: replacement.length };
  const unknownBytes = Buffer.alloc(65536, 'c'); const unknownRef = { version: createHash('sha256').update(unknownBytes).digest('hex'), bytes: unknownBytes.length };
  const unknown = store.beginBodyStage(id, 'item', 'text', unknownRef, { generation: 'unrelated-source', sequence: 0 });
  const newStage = store.beginBodyStage(id, 'item', 'text', next, { generation: 'source', sequence: 2 });
  store.stageBodyChunk(stage.stageId, 0, bytes.subarray(0, 65536));
  store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT COUNT(*) n FROM workbench_body_chunks WHERE version=?').get(ref.version)!.n, 12, 'concurrent begins cannot retire one another');
  store.stageBodyChunk(newStage.stageId, 0, replacement); store.validateBodyStage(newStage.stageId); store.finishBodyStage(newStage.stageId);
  store.mergeHistory(id, [{ id: 'item', kind: 'assistant', status: 'completed', text: replacement.subarray(0, 8192).toString(), bodies: { text: next }, sourceRevision: { generation: 'source', sequence: 2 } }]);
  assert.throws(() => store.stageBodyChunk(stage.stageId, 0, bytes.subarray(0, 65536)), { code: 'body_stage_superseded' });
  store.stageBodyChunk(unknown.stageId, 0, unknownBytes);
  store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT COUNT(*) n FROM workbench_body_chunks WHERE version=?').get(ref.version)!.n, 4);
  store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT 1 FROM workbench_bodies WHERE version=?').get(ref.version), undefined);
  assert.equal(db.prepare('SELECT transient_bytes FROM workbench_body_usage').get()!.transient_bytes, unknownBytes.length);
  assert.equal(db.prepare('SELECT reserved_bytes FROM workbench_body_usage').get()!.reserved_bytes, unknownBytes.length);
  store.mergeHistory(id, [{ id: 'item', kind: 'assistant', status: 'completed', text: 'new final content', sourceRevision: { generation: 'source', sequence: 3 } }]);
  for (let i = 0; i < 3; i++) store.advanceStorageMaintenance();
  assert.deepEqual(Buffer.from(store.readBody(id, 'item', 'text', next).data), replacement);
  assert.ok(db.prepare('SELECT 1 FROM workbench_body_stages WHERE id=?').get(unknown.stageId), 'different generations do not order each other');
});

test('upload cleanup uses the due-candidate index and finite batches while pinned history remains', t => {
  const root = mkdtempSync(join(tmpdir(), 'zhongshu-capacity-resource-'));
  const db = openDatabase(root, productMigrations);
  t.after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
  const store = createWorkbenchStore(db); const id = randomUUID();
  store.createConversation({ id, harnessId: 'codex', workspaceId: 'fixture', cwd: '/synthetic', configuration: { modelId: 'fixture', permissionId: 'fixture' } });
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6ZAAAAABJRU5ErkJggg==', 'base64');
  const pinned = store.resources.put(id, 'pinned.png', png); store.resources.pin(id, pinned.id, 'history');
  const archived = store.resources.put(id, 'native-output.png', Buffer.concat([png, Buffer.from('native-output')]), 'archive');
  for (let i = 0; i < 11; i++) store.resources.put(id, 'unused.png', Buffer.concat([png, Buffer.from(String(i))]));
  db.prepare('UPDATE workbench_resources SET created_at=0').run();
  store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT COUNT(*) n FROM workbench_resource_gc').get()!.n, 7);
  for (let i = 0; i < 3; i++) store.advanceStorageMaintenance();
  assert.equal(db.prepare('SELECT COUNT(*) n FROM workbench_resources').get()!.n, 2);
  assert.deepEqual(store.resources.get(id, pinned.id).data, png);
  assert.equal(store.resources.get(id, archived.id).name, 'native-output.png', 'unlinked archive output is not an expiring upload after a lost pin RPC');
  assert.ok(db.prepare('SELECT 1 FROM workbench_resource_refs WHERE owner_id=?').get('archive-stage:' + archived.id));
  store.resources.pin(id, archived.id, 'native-item');
  assert.equal(db.prepare('SELECT 1 FROM workbench_resource_refs WHERE owner_id=?').get('archive-stage:' + archived.id), undefined);
  assert.ok(db.prepare('SELECT 1 FROM workbench_resource_refs WHERE resource_id=? AND owner_id=?').get(archived.id, 'native-item'));
  const plan = db.prepare('EXPLAIN QUERY PLAN SELECT id,bytes FROM workbench_resource_gc WHERE created_at<? ORDER BY created_at,id LIMIT 4').all(Date.now());
  assert.ok(plan.some(row => String(row.detail).includes('workbench_resource_gc_due')));
});
